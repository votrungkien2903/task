#pragma once
#include "Matrix.h"

/// Абстрактный генератор: определяет способ заполнения матрицы связей (паттерн «Стратегия»).
class Generator {
public:
    /// Виртуальный деструктор (удаление через указатель на базовый класс).
    virtual ~Generator();

    /// Заполняет все элементы матрицы (полиморфный метод).
    virtual void Fill(Matrix& matrix) = 0;
};
